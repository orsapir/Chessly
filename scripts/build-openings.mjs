/**
 * Turns the Lichess opening database (5 TSVs, ~3800 lines) into one compact
 * data module. Move numbers are stripped - SAN alone identifies the line - and
 * the result is newline-delimited rather than JSON, which parses just as fast
 * and is a third the size.
 *
 *   node scripts/build-openings.mjs <dir-with-tsvs>
 */
import { readFileSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'

const source = process.argv[2]
if (!source) {
  console.error('usage: node scripts/build-openings.mjs <dir with a.tsv..e.tsv>')
  process.exit(1)
}

const rows = []
for (const letter of ['a', 'b', 'c', 'd', 'e']) {
  const text = readFileSync(join(source, `eco_${letter}.tsv`), 'utf8')
  for (const line of text.split('\n').slice(1)) {
    if (!line.trim()) continue
    const [eco, name, pgn] = line.split('\t')
    if (!eco || !name || !pgn) continue
    // "1. e4 e5 2. Nf3" -> "e4 e5 Nf3"
    const moves = pgn.replace(/\d+\.(\.\.)?\s*/g, '').trim().replace(/\s+/g, ' ')
    rows.push(`${moves}\t${eco}\t${name}`)
  }
}

rows.sort()
const body = rows.join('\n')
const out = `/**
 * Opening names from the Lichess opening database, which is itself built from
 * the ECO classification. Generated by scripts/build-openings.mjs - edit that
 * rather than this file.
 *
 * Each line is "<san moves>\\t<eco>\\t<name>", sorted, ${rows.length} of them.
 */
export const OPENING_DATA = ${JSON.stringify(body)}
`
writeFileSync('src/lib/openings.data.ts', out)
console.log(`${rows.length} openings, ${(body.length / 1024).toFixed(0)}KB of data`)
